"""GUI adapter for the cloned multiparser, with paragraph-safe extraction.

The upstream module supplies the reader URL, request headers/session and pacing.
Its CLI stays untouched; this adapter adds GUI callbacks and stricter completion.
"""
from __future__ import annotations

from hashlib import sha256
import importlib.util
from pathlib import Path
import re
import threading
from urllib.parse import parse_qs, urlencode, urljoin, urlsplit, urlunsplit

from bs4 import BeautifulSoup
import requests

from .text_tools import Book, Chapter, clean_text, html_text

UPSTREAM_FILE = Path(__file__).resolve().parents[1] / "upstream" / "multiparser.py"
if not UPSTREAM_FILE.is_file():
    raise ImportError("Не найден upstream/multiparser.py. Сначала склонируйте репозиторий.")
spec = importlib.util.spec_from_file_location("loveread_original", UPSTREAM_FILE)
upstream = importlib.util.module_from_spec(spec)
# Execute the retained source without placing generated bytecode in its git tree.
exec(compile(UPSTREAM_FILE.read_text(encoding="utf-8"), str(UPSTREAM_FILE), "exec"), upstream.__dict__)

BASE_URL = upstream.BASE_URL
BOOK_DELAY = upstream.BOOK_DELAY


class DownloadError(RuntimeError):
    pass


class PageNotFound(DownloadError):
    pass


class PartialBookError(DownloadError):
    def __init__(self, book, reason, expected=0):
        self.book = book
        self.expected = expected
        super().__init__(reason)


def normalize_reference(value: str) -> str:
    value = value.strip()
    base = urlsplit(BASE_URL)
    if value.isdigit():
        book_id = value
    else:
        if "://" not in value:
            value = "https://" + value
        parsed = urlsplit(value)
        if parsed.scheme not in ("http", "https") or parsed.username or parsed.password:
            raise ValueError("Введите ID книги или ссылку LoveRead.")
        if (parsed.hostname or "").removeprefix("www.") != (base.hostname or "").removeprefix("www."):
            raise ValueError(f"Нужна ссылка сайта {base.hostname} или числовой ID книги.")
        if parsed.path not in ("/view_global.php", "/read_book.php"):
            raise ValueError("Добавьте ссылку на книгу (view_global.php) или страницу чтения (read_book.php).")
        book_id = parse_qs(parsed.query).get("id", [""])[0]
    if not book_id.isdigit() or not 0 < int(book_id) < 10**16:
        raise ValueError("Не найден корректный числовой ID книги.")
    return BASE_URL + "?" + urlencode({"id": int(book_id), "p": 1})


def check_cancel(event):
    if event.is_set():
        raise InterruptedError("Загрузка остановлена.")


def get_html(url, cancelled, log, session=None):
    session = session or upstream.session
    for attempt in range(2):
        check_cancel(cancelled)
        try:
            response = session.get(url, timeout=(8, 20))
            if response.status_code == 404:
                raise PageNotFound("Страница не найдена (HTTP 404).")
            if response.status_code in (401, 403):
                raise DownloadError(f"Сайт отказал в доступе (HTTP {response.status_code}).")
            if response.status_code == 429:
                raise DownloadError("Сайт ограничил частоту запросов (HTTP 429). Повторите загрузку позже.")
            response.raise_for_status()
            check_cancel(cancelled)
            data = response.content
            # Some editions of the site still declare/use Windows-1251.
            declared = re.search(br'charset\s*=\s*["\']?([\w-]+)', data[:8192], re.I)
            encodings = [declared.group(1).decode("ascii")] if declared else []
            encodings += ["utf-8-sig", "cp1251"]
            for encoding in encodings:
                try:
                    return data.decode(encoding)
                except (UnicodeError, LookupError):
                    continue
            raise DownloadError("Не удалось прочитать кодировку страницы.")
        except requests.RequestException as exc:
            if attempt == 0:
                log("Временная ошибка сети. Повторяем запрос через 2 секунды…")
                if cancelled.wait(2):
                    raise InterruptedError("Загрузка остановлена.")
            else:
                raise DownloadError(f"Не удалось получить страницу: {exc}") from exc


def page_numbers(soup, book_id):
    numbers = set()
    content = soup.select_one("div.textBook")
    for node in soup.select("a[href], option[value]"):
        if content is not None and content in node.parents:
            continue
        href = node.get("href") or node.get("value") or ""
        parsed = urlsplit(urljoin(BASE_URL, href))
        if parsed.path != urlsplit(BASE_URL).path or (parsed.hostname or "").removeprefix("www.") != (urlsplit(BASE_URL).hostname or "").removeprefix("www."):
            continue
        query = parse_qs(parsed.query)
        if query.get("id", [str(book_id)])[0] != str(book_id):
            continue
        page = query.get("p", [""])[0]
        if page.isdigit() and 0 < int(page) <= 100000:
            numbers.add(int(page))
    for node in soup.select('select[name="p"] option[value]'):
        if str(node.get("value", "")).isdigit():
            value = int(node["value"])
            if value > 0:
                numbers.add(value)
    return numbers


def extract_page(soup):
    content = soup.select_one("div.textBook")
    if content is None:
        return ""
    # Work on a copy: pagination and metadata still use the original soup.
    content = BeautifulSoup(str(content), "html.parser")
    for node in content.select(".ads, .advert, .advertisement, .adsbygoogle, .pagination, .navigation, .social, .share, [id^='ad_']"):
        node.decompose()
    for node in content.select("sup"):
        if re.fullmatch(r"\d{1,4}", node.get_text(strip=True)):
            node.replace_with("[" + node.get_text(strip=True) + "]")
    # html_text preserves inline emphasis while putting paragraph blocks apart.
    return html_text(str(content))


def book_metadata(soup, book_id):
    title = ""
    author = ""
    for selector in ("h1", 'meta[property="og:title"]', "title"):
        node = soup.select_one(selector)
        if node:
            title = node.get("content") or node.get_text(" ", strip=True)
            if title:
                break
    for selector in ('[itemprop="author"]', 'a[href*="biography.php"]', ".author"):
        node = soup.select_one(selector)
        if node:
            author = clean_text(node.get_text(" ", strip=True))
            break
    title = re.sub(r"^(?:Читать\s+(?:онлайн\s+)?книгу|Читать\s+онлайн)\s*[:—-]?\s*", "", title, flags=re.I)
    title = re.sub(r"\s*(?:[-|—·]\s*)?(?:страница\s*\d+|читать\s+онлайн|онлайн\s+бесплатно).*$", "", title, flags=re.I)
    title = re.sub(r"\s*[-|—]\s*LoveRead.*$", "", title, flags=re.I)
    return clean_text(title).strip(" —-|") or f"Книга {book_id}", author


def fetch_book(reference, progress, log, cancelled):
    url = normalize_reference(reference)
    book_id = int(parse_qs(urlsplit(url).query)["id"][0])
    log(f"Книга {book_id}: получаем первую страницу…")
    progress(0, 0, f"Книга {book_id}: определяем страницы…")
    book = Book(f"Книга {book_id}", source=url)
    known_max = 0
    seen = set()
    limit = int(upstream.FALLBACK_MAX_PAGES)
    page = 1

    def incomplete(reason):
        if book.chapters:
            raise PartialBookError(book, reason, known_max)
        raise DownloadError(reason)

    while page <= limit:
        check_cancel(cancelled)
        if page > 1 and cancelled.wait(float(upstream.PAGE_DELAY)):
            raise InterruptedError("Загрузка остановлена.")
        page_url = BASE_URL + "?" + urlencode({"id": book_id, "p": page})
        try:
            markup = get_html(page_url, cancelled, log)
        except PageNotFound as exc:
            if page > 1 and not known_max:
                break
            incomplete(f"Не загружена страница {page}: {exc}")
        except DownloadError as exc:
            incomplete(f"Не загружена страница {page}: {exc}")
        soup = BeautifulSoup(markup, "html.parser")
        pages = page_numbers(soup, book_id)
        if pages:
            known_max = max(known_max, max(pages))
        if known_max > limit:
            incomplete(f"Сайт сообщил {known_max} страниц, больше защитного предела {limit}. Загрузка остановлена.")
        text = extract_page(soup)
        if not text:
            if page == 1:
                raise DownloadError("Текст книги не найден в блоке textBook. Проверьте ID, доступ к книге или разметку сайта.")
            # A blank response can be an access/error page, never proof of completion.
            incomplete(f"На странице {page} не найден текст. Книга может быть неполной.")
        digest = sha256(text.encode()).hexdigest()
        if digest in seen:
            if not known_max:
                log("Сайт повторил уже загруженную страницу: достигнут конец текста без пагинации.")
                break
            incomplete(f"Страница {page} повторяет ранее загруженный текст. Книга не отмечена полной.")
        if page == 1:
            book.title, book.author = book_metadata(soup, book_id)
        seen.add(digest)
        book.chapters.append(Chapter("", text))
        progress(page, known_max, f"{book.title} · страница {page}" + (f" из {known_max}" if known_max else " · ищем конец"))
        log(f"Страница {page}" + (f"/{known_max}" if known_max else "") + " получена.")
        if known_max and page >= known_max:
            break
        page += 1
    else:
        incomplete(f"Достигнут защитный предел {limit} страниц. Конец книги не подтверждён.")
    check_cancel(cancelled)
    if not book.chapters:
        raise DownloadError("Не удалось получить текст книги.")
    progress(len(book.chapters), len(book.chapters), f"{book.title} · текст готов")
    return book
